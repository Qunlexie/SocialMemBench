# Helper to make a turn
def T(idx, session_num, speaker_id, name, time_str, date_str, msg, challenges=None, reply=None):
    return {
        "turn_id": f"grp_b1c2d3e4_s{session_num:02d}_t{idx:03d}",
        "session_id": f"grp_b1c2d3e4_s{session_num:02d}",
        "speaker_persona_id": speaker_id,
        "speaker_display_name": name,
        "timestamp_label": time_str,
        "timestamp": f"{date_str}T{time_str.split(', ')[1].replace('am','').replace('pm','').strip()}:00",
        "message": msg,
        "message_index": idx + 1,
        "planted_challenges": challenges or [],
        "reply_to_turn_id": reply,
    }

def C(cid, ctype, subj, spkr, attr, val, evidence, implicitness, session_idx, turn_idx):
    return {
        "challenge_id": cid,
        "challenge_type": ctype,
        "subject_persona_id": subj,
        "speaker_persona_id": spkr,
        "fact_attribute": attr,
        "fact_value": val,
        "evidence_span": evidence,
        "implicitness_level": implicitness,
        "session_index": session_idx,
        "turn_index": turn_idx,
    }

