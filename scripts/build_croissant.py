def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Emit a Croissant metadata JSON-LD file for SocialMemBench."
    )
    p.add_argument("--out", type=Path, default=DEFAULT_OUT,
                   help=f"Output path (default: {DEFAULT_OUT}).")
    p.add_argument("--write", action="store_true",
                   help="Actually write the file. Default is dry-run (print only).")
    p.add_argument("--dry-run", action="store_true",
                   help="Force dry-run mode (default).")
    p.add_argument("--no-mlcroissant", action="store_true",
                   help="Skip mlcroissant validation; emit hand-rolled JSON-LD only.")
    p.add_argument("--hf-id", default=None,
                   help="HuggingFace dataset id. Defaults to HF_REPO_ID in .env.")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    dry_run = (not args.write) or args.dry_run
    hf_id = args.hf_id or _load_env_var(DEFAULT_ENV, "HF_REPO_ID")

    metadata: dict[str, Any]
    if args.no_mlcroissant:
        metadata = build_handrolled_croissant(hf_id)
        backend = "hand-rolled"
    else:
        meta = build_with_mlcroissant(hf_id)
        if meta is not None:
            metadata = meta
            backend = "mlcroissant"
        else:
            metadata = build_handrolled_croissant(hf_id)
            backend = "hand-rolled (mlcroissant not installed)"

    print(f"Croissant backend: {backend}")
    print(f"Dataset name     : {metadata.get('name')}")
    print(f"Version          : {metadata.get('version')}")
    print(f"Record sets      : "
          f"{[rs['@id'] for rs in metadata.get('recordSet', []) if rs.get('@type') == 'cr:RecordSet']}")
    print(f"Output path      : {args.out}")

    if dry_run:
        print("\nDRY-RUN: not writing. Re-run with --write to emit the JSON-LD file.")
        # Still print the first 600 chars so reviewers can sanity-check.
        preview = json.dumps(metadata, ensure_ascii=False, indent=2)[:600]
        print("\n--- preview ---")
        print(preview)
        print("...")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8") as f:
        json.dump(metadata, f, ensure_ascii=False, indent=2)
    print(f"Wrote {args.out}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
