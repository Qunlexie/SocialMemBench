"""
build_croissant.py — emit a NeurIPS-compliant Croissant metadata file.

Produces `data/croissant_metadata.json` (or anywhere via --out) describing
the SocialMemBench parquet release. This file is what NeurIPS 2026
Datasets-and-Benchmarks reviewers point Croissant validators at.

Two backends are supported:

  1. mlcroissant (preferred). If the `mlcroissant` package is importable,
     we build the metadata using its Pydantic-style classes, which gives us
     schema validation for free (`metadata.to_json()` is what we serialise).
  2. Hand-rolled JSON-LD fallback. If `mlcroissant` is not installed, we
     emit the same structure by hand. This is the path most likely to run
     in CI; the hand-rolled JSON has been cross-checked against the
     EverMemBench-Dynamic Croissant served by the HuggingFace Hub.

Both backends include the **Responsible AI** fields the NeurIPS Croissant
checklist asks for:
    - dataCollection
    - personalSensitiveInformation
    - dataBiases
    - citeAs (BibTeX)

Usage
-----
    python scripts/build_croissant.py --dry-run   # default: print + don't write
    python scripts/build_croissant.py --write
"""
