def _croissant_context() -> dict:
    """The standard MLCommons Croissant 1.1 JSON-LD context."""
    return {
        "@language": "en",
        "@vocab": "https://schema.org/",
        "arrayShape": "cr:arrayShape",
        "citeAs": "cr:citeAs",
        "column": "cr:column",
        "conformsTo": "dct:conformsTo",
        "containedIn": "cr:containedIn",
        "cr": "http://mlcommons.org/croissant/",
        "rai": "http://mlcommons.org/croissant/RAI/",
        "prov": "http://www.w3.org/ns/prov#",
        "data": {"@id": "cr:data", "@type": "@json"},
        "dataCollection": "cr:dataCollection",
        "dataType": {"@id": "cr:dataType", "@type": "@vocab"},
        "dct": "http://purl.org/dc/terms/",
        "extract": "cr:extract",
        "field": "cr:field",
        "fileObject": "cr:fileObject",
        "fileProperty": "cr:fileProperty",
        "fileSet": "cr:fileSet",
        "format": "cr:format",
        "includes": "cr:includes",
        "isArray": "cr:isArray",
        "isLiveDataset": "cr:isLiveDataset",
        "jsonPath": "cr:jsonPath",
        "key": "cr:key",
        "md5": "cr:md5",
        "parentField": "cr:parentField",
        "path": "cr:path",
        "recordSet": "cr:recordSet",
        "references": "cr:references",
        "regex": "cr:regex",
        "repeated": "cr:repeated",
        "replace": "cr:replace",
        "sc": "https://schema.org/",
        "separator": "cr:separator",
        "source": "cr:source",
        "subField": "cr:subField",
        "transform": "cr:transform",
    }


def _file_set(config_name: str) -> dict:
    return {
        "@type": "cr:FileSet",
        "@id": f"parquet-files-for-config-{config_name}",
        "containedIn": {"@id": "repo"},
        "encodingFormat": "application/x-parquet",
        "includes": f"{config_name}/*/*.parquet",
    }


def _split_record_set(config_name: str) -> dict:
    return {
        "@type": "cr:RecordSet",
        "dataType": "cr:Split",
        "key": {"@id": f"{config_name}_splits/split_name"},
        "@id": f"{config_name}_splits",
        "name": f"{config_name}_splits",
        "description": f"Splits for the {config_name} config.",
        "field": [
            {
                "@type": "cr:Field",
                "@id": f"{config_name}_splits/split_name",
                "dataType": "sc:Text",
            }
        ],
        "data": [{f"{config_name}_splits/split_name": "train"}],
    }


def _record_set_from_fields(
    config_name: str,
    description: str,
    fields: list[tuple[str, str, str]],
) -> dict:
    rs_fields = [
        {
            "@type": "cr:Field",
            "@id": f"{config_name}/split",
            "dataType": "sc:Text",
            "source": {
                "fileSet": {"@id": f"parquet-files-for-config-{config_name}"},
                "extract": {"fileProperty": "fullpath"},
                "transform": {
                    "regex": f"{config_name}/(?:partial-)?(train)/.+parquet$"
                },
            },
            "references": {"field": {"@id": f"{config_name}_splits/split_name"}},
        }
    ]
    for col, dtype, desc in fields:
        rs_fields.append({
            "@type": "cr:Field",
            "@id": f"{config_name}/{col}",
            "description": desc,
            "dataType": dtype,
            "source": {
                "fileSet": {"@id": f"parquet-files-for-config-{config_name}"},
                "extract": {"column": col},
            },
        })
    return {
        "@type": "cr:RecordSet",
        "@id": config_name,
        "description": description,
        "field": rs_fields,
    }


def build_handrolled_croissant(hf_id: str) -> dict:
    dataset_url = f"https://huggingface.co/datasets/{hf_id}"
    today = date.today().isoformat()
    repo_obj = {
        "@type": "cr:FileObject",
        "@id": "repo",
        "name": "repo",
        "description": "The HuggingFace git repository hosting the parquet release.",
        "contentUrl": f"{dataset_url}/tree/main",
        "encodingFormat": "git+https",
        "sha256": "https://github.com/mlcommons/croissant/issues/80",
    }

    distribution = [
        repo_obj,
        _file_set("networks"),
        _file_set("personas"),
        _file_set("conversations"),
        _file_set("qa"),
    ]

    record_sets = [
        _split_record_set("networks"),
        _record_set_from_fields(
            "networks",
            "One row per ego network: id, group type/size, edges, norms, metadata.",
            NETWORKS_FIELDS,
        ),
        _split_record_set("personas"),
        _record_set_from_fields(
            "personas",
            "One row per persona, foreign-keyed to network_id. Carries demographic "
            "fields and (in parquet) nested big_five / communication_profile / "
            "preferences structs.",
            PERSONAS_FIELDS,
        ),
        _split_record_set("conversations"),
        _record_set_from_fields(
            "conversations",
            "One row per conversation turn (long form, joinable on network_id).",
            CONVERSATIONS_FIELDS,
        ),
        _split_record_set("qa"),
        _record_set_from_fields(
            "qa",
            "One row per QA pair (Q1-Q9), with evidence anchors and QC scores.",
            QA_FIELDS,
        ),
    ]

    return {
        "@context": _croissant_context(),
        "@type": "sc:Dataset",
        "conformsTo": "http://mlcommons.org/croissant/1.1",
        "name": DATASET_NAME,
        "alternateName": [hf_id],
        "description": DATASET_DESCRIPTION,
        "url": dataset_url,
        "version": DATASET_VERSION,
        "datePublished": today,
        "license": DATASET_LICENSE,
        "inLanguage": DATASET_LANGUAGE,
        "keywords": [
            "AI",
            "Memory",
            "Social Groups",
            "benchmark",
            "conversational AI",
        ],
        "creator": [{"@type": "Person", "name": name} for name in AUTHORS],
        "citeAs": _citation_bibtex(hf_id),
        # Responsible AI fields (NeurIPS Croissant RAI v1.0 requirement).
        # Keys are emitted with explicit `rai:` / `prov:` prefixes per the
        # NeurIPS croissant-rai-checker (literal string-match validation).
        "dataCollection": DATA_COLLECTION,
        "rai:dataLimitations": DATA_LIMITATIONS,
        "rai:dataBiases": DATA_BIASES,
        "rai:personalSensitiveInformation": PERSONAL_SENSITIVE_INFORMATION,
        "rai:dataUseCases": DATA_USE_CASES,
        "rai:dataSocialImpact": DATA_SOCIAL_IMPACT,
        "rai:hasSyntheticData": HAS_SYNTHETIC_DATA,
        "prov:wasGeneratedBy": PROV_WAS_GENERATED_BY,
        "distribution": distribution,
        "recordSet": record_sets,
    }


# --------------------------------------------------------------------------- #
# mlcroissant backend (preferred, validates while building).
# --------------------------------------------------------------------------- #

def build_with_mlcroissant(hf_id: str) -> dict | None:
    """Try to build via mlcroissant. Returns a JSON-LD dict on success,
    or None if the library is missing.

    The mlcroissant API has shifted between minor versions; rather than pin
    a specific shape we try the modern Pydantic-style entry point first and
    fall back to None on any import or attribute error. Callers should fall
    back to build_handrolled_croissant().
    """
    try:
        import mlcroissant as mlc  # type: ignore
    except (ImportError, TypeError, SyntaxError):
        # ImportError: not installed.
        # TypeError/SyntaxError: installed but Python version too old (mlcroissant requires 3.10+).
        return None

    # Defer to the hand-rolled JSON-LD; mlcroissant.Metadata accepts a JSON-LD
    # dict via Metadata.from_json which validates against the spec without
    # forcing us to track the rapidly-evolving Pydantic API.
    json_ld = build_handrolled_croissant(hf_id)
    try:
        meta = mlc.Metadata.from_json(json_ld)
        # `to_json` round-trips through validation; if it fails, mlcroissant
        # raises and we surface the error to the user.
        return meta.to_json()
    except Exception as exc:  # pragma: no cover
        print(
            f"WARN: mlcroissant validation failed ({exc}); falling back to "
            "hand-rolled JSON-LD without validation.",
            file=sys.stderr,
        )
        return json_ld


